def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--picxel", type=Path, default=Path.home() / ".codex/skills/picxel")
    args = parser.parse_args()
    sys.path.insert(0, str(args.picxel / "scripts"))
    from px import Grid
    from picxel import load, check

    anchor = json.loads((BASE / "refs/goblin.anchor.json").read_text(encoding="utf-8"))
    colors = dict(zip("ABCDEFGHIJKLMN", anchor["palette"]))
    image = paint(colors)
    lookup = {tuple(bytes.fromhex(v[1:])): k for k, v in colors.items()}
    grid = Grid(128)
    for y in range(128):
        for x in range(128):
            rgba = image.getpixel((x, y))
            if rgba[3]:
                grid.put(lookup[rgba[:3]], (x, y))
    path = BASE / "concepts/goblin-concept.pxg"
    grid.write(path, "goblin-concept", "sprite", colors, palette="custom")
    sheet = load(path)
    errors, warnings = check(sheet)
    assert not errors, errors
    sheet.image().save(BASE / "concepts/goblin.png")
    report = {"method": "code-authored concept using Picxel Grid; no image-model inference",
              "source_pixels_resampled": False, "construction_canvas": [128, 128],
              "requested_output": [64, 64], "palette_colors": len(colors),
              "reference_sha256": hashlib.sha256((BASE / "refs/goblin.png").read_bytes()).hexdigest(),
              "errors": errors, "warnings": warnings}
    (BASE / "concepts/method.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report))


if __name__ == "__main__":
    main()
