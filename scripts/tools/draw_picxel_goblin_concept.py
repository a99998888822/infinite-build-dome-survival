class Drawing:
    """Coordinates are hand-authored in the reference's 384px layout space."""
    def __init__(self, colors):
        self.image = Image.new("RGBA", (128, 128))
        self.draw = ImageDraw.Draw(self.image)
        self.colors = colors

    @staticmethod
    def xy(point):
        x, y = point
        return round(64 + (x - 192) * 123 / 360), round(2 + (y - 14) * 123 / 360)

    def p(self, color, points):
        fill = (0, 0, 0, 0) if color == "." else self.colors[color]
        self.draw.polygon([self.xy(p) for p in points], fill=fill)

    def l(self, color, points, width=2):
        self.draw.line([self.xy(p) for p in points], fill=self.colors[color], width=width)


