"""Pack fixed-window, nearest sampled, shared production atlases. UTF-8 everywhere."""
from pathlib import Path
from PIL import Image
import numpy as np
import json

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / 'artifacts/reviews/spell-baked-integration/raw'
OUT = ROOT / 'assets/effects/spells_baked'
OUT.mkdir(parents=True, exist_ok=True)
manifest = json.loads((RAW/'manifest.json').read_text(encoding='utf-8'))
definitions = {}
for key, info in manifest.items():
    if key == 'strike_points':
        continue
    frames = []
    for i in range(info['count']):
        # Transparent GPU readback contains premultiplied RGB. PNG playback
        # uses straight alpha, so undo it once to avoid darkening the palette.
        pixels = np.array(Image.open(RAW/key/f'{i:03d}.png').convert('RGBA'))
        alpha = pixels[:,:,3:4].astype(np.float32)
        pixels[:,:,:3] = np.clip(np.rint(pixels[:,:,:3].astype(np.float32)*255.0/np.maximum(alpha,1.0)),0,255).astype(np.uint8)
        frames.append(Image.fromarray(pixels))
    bounds = [im.getchannel('A').getbbox() for im in frames]
    bounds = [b for b in bounds if b]
    assert bounds, key
    crop = [max(0,min(b[0] for b in bounds)-2),max(0,min(b[1] for b in bounds)-2),min(480,max(b[2] for b in bounds)+2),min(360,max(b[3] for b in bounds)+2)]
    w,h = crop[2]-crop[0],crop[3]-crop[1]
    cols = min(8,info['count'])
    sheet = Image.new('RGBA',(w*cols,h*((len(frames)+cols-1)//cols)))
    for i, im in enumerate(frames):
        sheet.paste(im.crop(crop),((i%cols)*w,(i//cols)*h))
    sheet.save(OUT/f'{key}.png',optimize=True)
    definitions[key] = dict(size=[w,h],origin=[crop[0]-240,crop[1]-245],count=len(frames),columns=cols,fps=18)
    # Keep the project's pixel texture import policy, without hand-made UIDs.
    import_path = OUT/f'{key}.png.import'
    if not import_path.exists():
        import_path.write_text('[remap]\nimporter="texture"\ntype="CompressedTexture2D"\n\n[params]\ncompress/mode=0\nmipmaps/generate=false\nprocess/fix_alpha_border=false\n',encoding='utf-8')
(OUT/'manifest.json').write_text(json.dumps(definitions,indent=2),encoding='utf-8')
(OUT/'strike_points.json').write_text(json.dumps(manifest['strike_points']),encoding='utf-8')
source = 'extends RefCounted\n## Generated by scripts/tools/pack_selected_spells.py. Shared textures, no runtime baking.\n'
source += 'const DEFINITIONS := '+json.dumps(definitions)+'\n'
source += 'const TEXTURES := {\n'+',\n'.join('    "'+key+'": preload("res://assets/effects/spells_baked/'+key+'.png")' for key in definitions)+'\n}\n'
(ROOT/'scripts/effects/selected_spell_frames.gd').write_text(source,encoding='utf-8')
# Third-party notices are versioned beside the atlases, independent of local reviews.
for name in ['PIXELFX_LICENSE','PIXELFX_NOTICE.md']:
    assert (OUT/name).is_file(), name
print('Packed:',{k:v['size'] for k,v in definitions.items()})
print('RGBA8 MiB:',sum(Image.open(OUT/f'{key}.png').width*Image.open(OUT/f'{key}.png').height*4 for key in definitions)/1024**2)
